export async function getPromos(): Promise<PromoCard[]> {
  // The Philippines uses UTC+08:00 year-round. Build the local calendar
  // date directly to avoid relying on Intl locale formatting during prerender.
  const manilaNow = new Date(Date.now() + 8 * 60 * 60 * 1000);
  const todayInManila = manilaNow.toISOString().slice(0, 10);

  return PROMOTIONS
    .filter((promo) => isPublicPromoOnDate(promo, todayInManila))
    .sort(
      (a, b) =>
        new Date(b.publishedAt ?? 0).getTime() -
        new Date(a.publishedAt ?? 0).getTime()
    );
}

export async function getPricingTables(): Promise<PricingTable[]> {
  return MOCK_PRICING_TABLES;
}


/** Return every promotion for Admin management, including inactive offers. */
export async function getAllPromos(): Promise<PromoCard[]> {
  return [...PROMOTIONS];
}
